// Writes apps/server/src/mcp/book-chapters.ts from docs/vision/book/*.md, so the server serves
// the same text the docs show (no file reads at run time; the Vercel bundle has no docs folder).
// Run after editing a chapter: pnpm book:gen. book-tool.test.ts fails when it is stale.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import * as prettier from "prettier";

const root = join(import.meta.dirname, "..");
const dir = join(root, "docs/vision/book");
const IDS = {
  "00": "contents",
  "01": "start-here",
  "02": "about-me",
  "03": "notebooks",
  "04": "inbox",
  "05": "board",
  "06": "across",
  "07": "approval",
  "08": "recipes",
  "09": "errors",
  10: "your-pages",
};

function chapters() {
  const out = {};
  for (const file of readdirSync(dir).sort()) {
    const id = IDS[file.slice(0, 2)];
    if (id && file.endsWith(".md"))
      out[id] = readFileSync(join(dir, file), "utf8");
  }
  return out;
}

function render() {
  return [
    "// Generated by tools/gen-book.mjs from docs/vision/book/*.md. Do not edit by hand.",
    `export const BOOK_CHAPTERS: Record<string, string> = ${JSON.stringify(chapters(), null, 2)};`,
    "",
  ].join("\n");
}

const out = join(root, "apps/server/src/mcp/book-chapters.ts");
const config = (await prettier.resolveConfig(out)) ?? {};
writeFileSync(
  out,
  await prettier.format(render(), { ...config, filepath: out }),
);
console.log("wrote apps/server/src/mcp/book-chapters.ts");
